// Unlisted entries remain available to existing direct URLs.
function selectProjects(ids: readonly string[]): CaseStudy[] {
  return ids.map(id => {
    const project = caseStudies.find(project => project.id === id);
    if (!project) throw new Error('Unknown selected project: ' + id);
    return project;
  });
}
export const featuredProjects = selectProjects(projectSelection.featured);
export const moreProjects = selectProjects(projectSelection.more);
export const listedProjects = [...featuredProjects, ...moreProjects];
export function matchesProjectFilter(project: CaseStudy, filter: string): boolean {
  if (!listedProjects.some(item => item.id === project.id)) return false;
  if (filter === 'all') return true;
  return project.categories?.includes(filter as ProjectCategory) ?? false;
}
export function nextListedProject(id: string): CaseStudy {
  return listedProjects[(listedProjects.findIndex(project => project.id === id) + 1) % listedProjects.length];
}
